#!/usr/bin/env python3
"""Export bring-up vectors from the reference model (tb/mantis_ref.py).

  python3 bringup/export_vectors.py            # writes bringup/vectors.py

Each vector is one complete computation as the host sees it at the pins:
CLEAR with the two format bits, a stream of WRITE bytes, then 8 READ bytes.
The output is plain Python (strings and tuples only) so that it imports on the
demo board's MicroPython, which cannot run the Fraction-based model.
Regenerate whenever the reference model changes.
"""
import os
import random
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "tb"))
from mantis_ref import matmul, rand_matmul, readout_bytes, write_stream  # noqa: E402

SEED = 2026
ONE4, TWO4, SIXTEEN4 = 0x38, 0x40, 0x58          # E4M3FN 1, 2, 16
ONE5, MONE5, INF5, MINF5, MAX5 = 0x3C, 0xBC, 0x7C, 0xFC, 0x7B   # E5M2 1, -1, +inf, -inf, 57344

# (name, fmt_a, fmt_b, A, B): spec worked examples (docs/spec.md R1 to R9)
DIRECTED = [
    ("R1 example [[1,2],[3,4]] x [[5,6],[7,8]]", 0, 0,
     [[0x38, 0x40], [0x44, 0x48]], [[0x4A, 0x4C], [0x4E, 0x50]]),
    ("R3 RNE every step: 16*16 + 1 + 1 = 256", 0, 0,
     [[SIXTEEN4, ONE4, ONE4], [ONE4] * 3], [[SIXTEEN4, ONE4], [ONE4, ONE4], [ONE4, ONE4]]),
    ("R5 E5M2 1 * 57344", 1, 1, [[ONE5], [ONE5]], [[MAX5, ONE5]]),
    ("R6 A E4M3FN, B E5M2", 0, 1, [[ONE4], [ONE4]], [[ONE5, ONE5]]),
    ("R7 NaN persists", 0, 0, [[0x7F, ONE4], [ONE4, ONE4]], [[ONE4, ONE4], [ONE4, ONE4]]),
    ("R8 +inf and -inf", 1, 1, [[INF5, ONE5], [MINF5, ONE5]], [[ONE5, ONE5], [ONE5, MONE5]]),
    ("R9 1 - 1 = +0", 1, 1, [[ONE5, ONE5], [ONE5, ONE5]], [[ONE5, ONE5], [MONE5, ONE5]]),
    ("R4 E4M3FN max 448 * 448", 0, 0, [[0x7E], [0x7E]], [[0x7E, 0x7E]]),
]


def vector(name, fa, fb, A, B):
    return (name, fa, fb, bytes(write_stream(A, B)).hex(), bytes(readout_bytes(matmul(A, B, fa, fb))).hex())


def main(out=os.path.join(HERE, "vectors.py")):
    rng = random.Random(SEED)
    rows = [vector(*d) for d in DIRECTED]
    for i in range(48):                              # random K, formats; some specials
        A, B, fa, fb = rand_matmul(rng, rng.randint(1, 16), finite=rng.random() < 0.8)
        rows.append(vector("random %d K=%d" % (i, len(A[0])), fa, fb, A, B))
    for fa in (0, 1):                                # long finite streams
        A, B, _, _ = rand_matmul(rng, 64, fa, 1 - fa)
        rows.append(vector("stream K=64 fmt=(%d,%d)" % (fa, 1 - fa), fa, 1 - fa, A, B))
    with open(out, "w") as f:
        f.write('"""Generated by bringup/export_vectors.py from tb/mantis_ref.py (seed %d).\n'
                'Do not edit; regenerate.\n\n'
                'Each entry: (name, fmt_a, fmt_b, WRITE bytes as hex, 8 expected READ bytes as hex).\n'
                '"""\n\nVECTORS = [\n' % SEED)
        for name, fa, fb, w, r in rows:
            f.write("    (%r, %d, %d,\n     %r,\n     %r),\n" % (name, fa, fb, w, r))
        f.write("]\n")
    print("wrote %d vectors to %s" % (len(rows), os.path.relpath(out)))


if __name__ == "__main__":
    main()
